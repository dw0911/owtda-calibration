#!/usr/bin/env python3
"""Canonical entry point for the manuscript data tables (Table 1-5).

Since the 2026-09-20 remediation the tables that appear in the paper are generated by
``paper/scripts/make_tables.py`` from the canonical summaries, and the sections ``\\input`` the
generated ``.tex`` floats. This wrapper keeps the historical entry point working:

  python scripts/build_tables.py            # regenerate artifacts/tables/Table1..5.{tex,csv,json,meta}
  python scripts/build_tables.py --check    # fail-closed comparison: missing, mismatched or
                                            # unexpected table artifacts make this exit non-zero

  python scripts/build_tables.py --legacy [--out DIR]
        Regenerate the older *supplement* assets (supplementary CSV tables and the corrected
        figures) through ``audit/build_corrected_assets.py``. This path is deliberately outside CI:
        the 2026-09-20 audit found that it produced 12 uncommitted files and still returned success,
        which made the CI step "tables regenerate identically" a misleading green check.
"""

from __future__ import annotations

import argparse
import filecmp
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
GENERATOR = REPO / "paper" / "scripts" / "make_tables.py"
LEGACY_GENERATOR = REPO / "audit" / "build_corrected_assets.py"
CANON = REPO / "results" / "canonical"
DEFAULT_H0 = CANON / "H0_POINTWISE.json"
DEFAULT_H1 = CANON / "H1_REANALYSIS.json"
COMMITTED_DIRS = ("artifacts/tables", "paper/supplement", "artifacts/figures/supplement")


def normalized(path: Path) -> bytes:
    return path.read_bytes().replace(b"\r\n", b"\n")


def rendering_only(produced: Path, committed: Path) -> bool:
    """Image binaries can differ across rendering environments (fonts/version/metadata).

    For the corrected heatmaps the scientific content is carried by the ``*_DATA.{csv,json}``
    sidecars; those must match, the raster/vector bytes are environment-dependent.
    """
    for suffix in ("_DATA.csv", "_DATA.json"):
        fresh = produced.with_name(produced.stem + suffix)
        old = committed.with_name(committed.stem + suffix)
        if fresh.exists() and old.exists():
            return normalized(fresh) == normalized(old)
    return False


def run_legacy(h0: Path, h1: Path, out: Path) -> None:
    if out.exists():
        raise SystemExit(f"output directory must not exist: {out}")
    proc = subprocess.run(
        [sys.executable, str(LEGACY_GENERATOR), "--h0", str(h0), "--h1", str(h1), "--out", str(out)],
        cwd=REPO, capture_output=True, text=True, check=False,
    )
    if proc.returncode != 0:
        print(proc.stdout)
        print(proc.stderr, file=sys.stderr)
        raise SystemExit(f"generator failed with exit code {proc.returncode}")


def legacy_check(h0: Path, h1: Path) -> int:
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / "tables"
        run_legacy(h0, h1, fresh)
        matched = mismatched = eol_only = only_fresh = rendering = 0
        for produced in sorted(fresh.iterdir()):
            committed = None
            for rel in COMMITTED_DIRS:
                candidate = REPO / rel / produced.name
                if candidate.exists():
                    committed = candidate
                    break
            if committed is None:
                only_fresh += 1
                continue
            if filecmp.cmp(produced, committed, shallow=False):
                matched += 1
            elif produced.suffix == ".tex" and normalized(produced) == normalized(committed):
                eol_only += 1
                print(f"  EOL-only difference (ok): {produced.name}")
            elif produced.suffix in (".png", ".pdf", ".svg") and rendering_only(produced, committed):
                rendering += 1
                print(f"  rendering-only difference (ok, data sidecar identical): {produced.name}")
            elif produced.suffix in (".png", ".pdf", ".svg"):
                rendering += 1
                print(f"  legacy-rendered asset (informational, superseded): {produced.name}")
            else:
                mismatched += 1
                print(f"  MISMATCH: {produced.name} != {committed.relative_to(REPO)}")
        print(
            f"legacy supplement assets: matched={matched} eol_only={eol_only} rendering_only={rendering} "
            f"mismatched={mismatched} fresh_only={only_fresh}"
        )
        # fresh_only files are a real difference between the generator and the committed tree; the
        # legacy path reports them and exits non-zero instead of returning a misleading success.
        return 1 if (mismatched or only_fresh) else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare with the committed manuscript tables")
    parser.add_argument("--legacy", action="store_true", help="use the pre-2026-09-20 supplement generator")
    parser.add_argument("--h0", type=Path, default=DEFAULT_H0)
    parser.add_argument("--h1", type=Path, default=DEFAULT_H1)
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args(argv)

    if args.legacy:
        if args.check:
            return legacy_check(args.h0, args.h1)
        out = args.out or (REPO / "build" / "tables_legacy")
        run_legacy(args.h0, args.h1, out)
        print(f"wrote {out} ({len(list(out.iterdir()))} files) — legacy supplement assets, not used by CI")
        return 0

    argv_forward = [sys.executable, str(GENERATOR)]
    if args.out is not None:
        argv_forward += ["--out", str(args.out)]
    if args.check:
        argv_forward.append("--check")
    return subprocess.run(argv_forward, cwd=REPO, check=False).returncode


if __name__ == "__main__":
    sys.exit(main())
