#!/usr/bin/env python3
"""Canonical entry point for the manuscript data tables (Table 1-5).

The tables that appear in the paper are generated by ``paper/scripts/make_tables.py``
from the canonical summaries, and the sections ``\\input`` the generated ``.tex`` floats.
This wrapper keeps the historical entry point working:

  python scripts/build_tables.py            # regenerate artifacts/tables/Table1..5.{tex,csv,json,meta}
  python scripts/build_tables.py --check    # fail-closed comparison: missing, mismatched or
                                            # unexpected table artifacts make this exit non-zero
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
GENERATOR = REPO / "paper" / "scripts" / "make_tables.py"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="compare with the committed manuscript tables")
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args(argv)

    argv_forward = [sys.executable, str(GENERATOR)]
    if args.out is not None:
        argv_forward += ["--out", str(args.out)]
    if args.check:
        argv_forward.append("--check")
    return subprocess.run(argv_forward, cwd=REPO, check=False).returncode


if __name__ == "__main__":
    sys.exit(main())
